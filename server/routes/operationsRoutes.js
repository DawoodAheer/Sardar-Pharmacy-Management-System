import express from 'express';
import { authorize, protect } from '../middleware/authMiddleware.js';
import * as operations from '../controllers/operationsController.js';
import { getSystemStatus } from '../utils/systemMonitor.js';
import { dashboardSummary } from '../controllers/dashboardController.js';
const router = express.Router();
router.use(protect, authorize('superadmin', 'pharmacist'));
router.get('/system', authorize('superadmin'), getSystemStatus);
router.get('/summary', dashboardSummary);
router.get('/batch-alerts', operations.batchExpiryAlerts);
router.get('/batches', operations.listBatches);
router.post('/batches/:id', operations.receiveBatch);
router.get('/suppliers', operations.listSuppliers);
router.post('/suppliers', operations.createSupplier);
router.get('/purchases', operations.listInvoices);
router.post('/purchases', operations.receiveInvoice);
router.post('/purchases/:id/pay', authorize('superadmin'), operations.payInvoice);
router.post('/purchases/:id/return', authorize('superadmin'), operations.returnPurchase);
router.get('/credit/:id/statement', operations.getCreditStatement);
router.patch('/credit/:id/due-date', operations.updateCreditDueDate);
router.get('/cash', operations.getCashSession);
router.post('/cash', authorize('superadmin'), operations.saveCashSession);
export default router;
